// 返回参数     void
// 使用示例     vofa_snapshot();
//-------------------------------------------------------------------------------------------------------------------
void vofa_snapshot(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按发送分频输出最新波形快照
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_poll(void);

// 下行只有一条命令，ASCII 行，'\r\n' 或 '\n' 结束：
//   <参数名> <值>
// 参数名白名单就是 vofa.c 里 s_tune_tbl 的 24 个环 PID，其余参数一律用车上的按键改。
// 应答只有 ack:1.000 / ack:0.000。数值必须完整解析，NaN 与无穷一律拒绝。
// 架空点动期间拒绝改参数；闭环测试期间只放行当前轴、当前最高启用环之内的增益；
// 三轴平衡(START_BALANCE)期间 24 个全放行，整定本来就要边跑边改。
// 波形模式由菜单页决定，命令侧不能切波形。
// 本协议只做看波形和调参，不提供任何电机启停命令，发车与停车只能用车上的实体键。
// 24 条命令的完整清单见 调参命令.md。

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     解析并执行无线串口下行调参命令，由主循环调用
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_cmd_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_cmd_poll(void);

#endif // VOFA_H_
