#ifndef VOFA_H_
#define VOFA_H_

#include "zf_common_headfile.h"

// 波形模式
typedef enum
{
    VOFA_OFF = 0,       // 关闭波形输出
    VOFA_IMU_RAW,       // IMU 原始数据，6 通道
    VOFA_ATT,           // Roll、Pitch、Yaw，3 通道
    VOFA_ROLL,          // Roll 串级数据，7 通道
    VOFA_PITCH,         // Pitch 串级数据，7 通道
    VOFA_YAW,           // Yaw 串级数据，6 通道
    VOFA_TRACK,         // 循迹数据，10 通道
    VOFA_MOTOR,         // 电机指令与转速反馈，5 通道
    VOFA_DASH,          // 综合面板数据，9 通道
} vofa_mode_t;

// 调参轴
typedef enum
{
    TUNE_AXIS_ROLL = 0,     // 横滚轴
    TUNE_AXIS_PITCH,        // 俯仰轴
    TUNE_AXIS_YAW,          // 航向轴
    TUNE_AXIS_MAX
} tune_axis_t;

// 调参环
typedef enum
{
    TUNE_RING_RATE = 0,     // 角速度环
    TUNE_RING_ANGLE,        // 角度环
    TUNE_RING_VEL,          // 速度环或飞轮回收环
    TUNE_RING_MAX
} tune_ring_t;

extern volatile vofa_mode_t g_vofa_mode;    // 当前波形模式
extern volatile uint8       g_vofa_div;     // 发送分频
extern volatile tune_axis_t g_tune_axis;    // 当前调参轴
extern volatile tune_ring_t g_tune_ring;    // 当前调参环

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     上行发送队列初始化
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_init();
//-------------------------------------------------------------------------------------------------------------------
void vofa_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     将发送队列数据写入 UART0 硬件 FIFO
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_tx_pump();
//-------------------------------------------------------------------------------------------------------------------
void vofa_tx_pump(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     根据波形模式更新通道快照
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_snapshot();
//-------------------------------------------------------------------------------------------------------------------
void vofa_snapshot(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按发送分频输出最新波形快照
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_poll(void);

// 下行命令以 ASCII 行传输，使用 '\n' 或 '\r' 结束。
// axis roll|pitch|yaw|next：切换调参轴。
// ring rate|angle|vel|next：切换调参环。
// kp|kpm|ki|kd <value>：修改当前调参环增益。
// set <name> <value>、get <name>、list：修改或读取参数。
// save：保存参数；wave <mode>：切换波形；ping：通信检测。
// 应答格式为 pid:<...>、par:<...> 和 ack:<code>。

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     接收并执行 UART0 下行调参命令
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_cmd_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_cmd_poll(void);

#endif // VOFA_H_
