#ifndef VOFA_H_
#define VOFA_H_

#include "zf_common_headfile.h"

// UART0 上行波形，VOFA+ FireWater 格式 <tag>:v0,v1,...\n，通道按位置对应。
// 同一模式下通道数必须恒定，否则 FireWater 会错位。
typedef enum
{
    VOFA_OFF = 0,       // 关闭波形输出
    VOFA_IMU_RAW,       // imu  : IMU 原始六轴，6 通道
    VOFA_ATT,           // att  : Roll、Pitch、Yaw，3 通道
    VOFA_ROLL,          // roll : Roll 串级各环，7 通道
    VOFA_PITCH,         // pit  : Pitch 串级各环，7 通道
    VOFA_YAW,           // yaw  : Yaw 串级各环，6 通道
    VOFA_TRACK,         // trk  : 循迹偏差与丢线统计，10 通道
    VOFA_MOTOR,         // mot  : 三电机指令与转速回读，5 通道
    VOFA_DASH,          // dash : 综合面板，9 通道
} vofa_mode_t;

// 调参轴
typedef enum
{
    TUNE_AXIS_ROLL = 0,     // 横滚轴
    TUNE_AXIS_PITCH,        // 俯仰轴
    TUNE_AXIS_YAW,          // 航向轴
    TUNE_AXIS_MAX
} tune_axis_t;

// 调参环
typedef enum
{
    TUNE_RING_RATE = 0,     // 角速度环
    TUNE_RING_ANGLE,        // 角度环
    TUNE_RING_VEL,          // 速度环或飞轮回收环
    TUNE_RING_MAX
} tune_ring_t;

extern volatile vofa_mode_t g_vofa_mode;    // 当前波形模式
extern volatile uint8       g_vofa_div;     // 发送分频
extern volatile tune_axis_t g_tune_axis;    // 当前调参轴
extern volatile tune_ring_t g_tune_ring;    // 当前调参环

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     上行发送队列初始化
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_init();
//-------------------------------------------------------------------------------------------------------------------
void vofa_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     将发送队列数据写入 UART0 硬件 FIFO
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_tx_pump();
//-------------------------------------------------------------------------------------------------------------------
void vofa_tx_pump(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     根据波形模式更新通道快照
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_snapshot();
//-------------------------------------------------------------------------------------------------------------------
void vofa_snapshot(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     按发送分频输出最新波形快照
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_poll(void);

// UART0 下行命令，ASCII 行，'\n' 或 '\r' 结束：
//   axis roll|pitch|yaw|next      切换调参轴
//   ring rate|angle|vel|next      切换调参环
//   kp|ki|kd <value>              改当前轴当前环的增益
//   set <name> <value>            按名字改参数
//   get <name>                    读单个参数
//   list                          回传全部参数
//   save                          写 Flash
//   wave off|imu|att|roll|pit|yaw|trk|mot|dash 切波形
//   ping                          通信检测
// 应答格式为 pid:<...>、par:<...> 和 ack:<0|1>。
// 数值字段必须完整合法；电机测试、点动或发车期间禁止切轴、切环、切波形和保存。
// 闭环测试期间仅允许修改当前轴已启用串级范围内的增益。
// 本协议只做看波形和调参，不提供任何电机启停命令，发车与停车只能用车上的实体键。

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     接收并执行 UART0 下行调参命令
// 参数说明     void
// 返回参数     void
// 使用示例     vofa_cmd_poll();
//-------------------------------------------------------------------------------------------------------------------
void vofa_cmd_poll(void);

#endif // VOFA_H_
