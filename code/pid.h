#ifndef PID_H_
#define PID_H_

#include "zf_common_headfile.h"

// 一个结构同时给位置式和增量式用
typedef struct {
    float kp, ki, kd;            // 三个增益，由菜单或串口实时改
    float imax;                  // 积分限幅，只对位置式生效
    float out_p, out_i, out_d;   // 三个分项的输出，调试用
    float out;                   // 本环输出
    float integrator;            // 位置式的积分累加量
    float last_error;            // 上一拍误差
    float last_derivative;       // 上一拍的误差增量，增量式算二阶差分用
} pid_t;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置 PID 参数并清除历史状态
// 参数说明     p               PID 结构体, kp/ki/kd 为系数, imax 为积分限幅
// 返回参数     void
// 使用示例     pid_set(&p_vel_pid, P_VEL_KP, P_VEL_KI, P_VEL_KD, P_VEL_IMAX);
//-------------------------------------------------------------------------------------------------------------------
void  pid_set(pid_t *p, float kp, float ki, float kd, float imax);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清除 PID 积分与误差历史
// 参数说明     p               PID 结构体指针
// 返回参数     void
// 使用示例     pid_reset(&p_vel_pid);
//-------------------------------------------------------------------------------------------------------------------
void  pid_reset(pid_t *p);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     算一拍位置式 PID，只对积分限幅，输出不限幅
// 参数说明     p/error         PID 实例与当前误差
// 返回参数     float           本次绝对输出
// 使用示例     pid_loc_calc(&p_angle_pid, p_vel_pid.out - att.pitch + zero);
//-------------------------------------------------------------------------------------------------------------------
float pid_loc_calc(pid_t *p, float error);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     算一拍位置式 PID，带输出限幅与条件积分抗饱和。外层还要限幅的环一律用这个
// 参数说明     p/error/low/high PID 实例、当前误差、输出下限与上限
// 返回参数     float           限幅后的输出
// 使用示例     pid_loc_calc_limited(&r_rate_pid, error, -limit, limit);
//-------------------------------------------------------------------------------------------------------------------
float pid_loc_calc_limited(pid_t *p, float error, float low, float high);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     算一拍带输出限幅的增量式 PID，积分只在不会继续推向饱和时生效
// 参数说明     p/error/low/high PID 实例、当前误差、输出下限与上限
// 返回参数     float           限幅后的累计输出
// 使用示例     pid_inc_calc_limited(&r_rate_pid, error, -limit, limit);
//-------------------------------------------------------------------------------------------------------------------
float pid_inc_calc_limited(pid_t *p, float error, float low, float high);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     浮点限幅
// 参数说明     amt/low/high    输入值与上下限
// 返回参数     float           限幅后的值
// 使用示例     offset = constrain_float(offset, -limit, limit);
//-------------------------------------------------------------------------------------------------------------------
float constrain_float(float amt, float low, float high);

#endif
