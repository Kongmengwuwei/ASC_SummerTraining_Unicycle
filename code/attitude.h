#ifndef ATTITUDE_H_
#define ATTITUDE_H_

#include "zf_common_headfile.h"

typedef struct
{
    float roll;         // 横滚角，车体左右倾，单位 deg
    float pitch;        // 俯仰角，车体前后倾，单位 deg
    float yaw;          // 连续航向角，永不清零，单位 deg
    float yaw_wrapped;  // 显示用航向角，范围 (-180, 180]

    float roll_rate;    // 横滚角速度，单位 deg/s
    float pitch_rate;   // 俯仰角速度，单位 deg/s
    float yaw_rate;     // 航向角速度，单位 deg/s
} attitude_t;

extern attitude_t att;

typedef struct
{
    float acc_norm;     // 加速度模长，单位 g
    float bias_z;       // Mahony Z 轴零偏估计，单位 rad/s
    uint8 acc_valid;    // 加速度校正有效标志
} att_diag_t;

extern att_diag_t att_diag;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化 Mahony 四元数姿态解算状态
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_init();
//-------------------------------------------------------------------------------------------------------------------
void attitude_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     使用 IMU 原始数据更新车体系角速度
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_update_rate();
//-------------------------------------------------------------------------------------------------------------------
void attitude_update_rate(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新 Mahony 四元数和欧拉角
// 参数说明     void
// 返回参数     void
// 使用示例     attitude_update();
//-------------------------------------------------------------------------------------------------------------------
void attitude_update(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查姿态解算冷启动收敛状态
// 参数说明     void
// 返回参数     uint8           1 表示收敛完成，0 表示尚未完成
// 使用示例     uint8 ready = attitude_converged();
//-------------------------------------------------------------------------------------------------------------------
uint8 attitude_converged(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查四元数是否发生过发散
// 参数说明     void
// 返回参数     uint8           1 表示发生过发散，0 表示正常
// 使用示例     uint8 fault = attitude_diverged();
//-------------------------------------------------------------------------------------------------------------------
uint8 attitude_diverged(void);

#endif
