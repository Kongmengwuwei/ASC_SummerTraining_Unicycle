#ifndef PERSPECTIVE_H
#define PERSPECTIVE_H

#include "zf_common_headfile.h"
#include "board_config.h"


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     查询逆透视矩阵是否已标定可用
// 参数说明     void
// 返回参数     uint8            1=可用 0=未标定，调用方要退回图像坐标系的老路径
// 使用示例     if (ipm_ready()) { ... }
//-------------------------------------------------------------------------------------------------------------------
uint8 ipm_ready(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     清除当前逆透视矩阵
// 参数说明     void
// 返回参数     void
// 使用示例     ipm_clear();
//-------------------------------------------------------------------------------------------------------------------
void ipm_clear(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     载入一组逆透视系数并做可用性检查
// 参数说明     h                行优先的 9 个系数，h[8] 为 0 视为未标定
// 返回参数     uint8            1=载入成功
// 使用示例     ipm_load(g_param.ipm_h);
//-------------------------------------------------------------------------------------------------------------------
uint8 ipm_load(const float h[9]);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读回当前逆透视系数
// 参数说明     h                输出，行优先的 9 个系数
// 返回参数     void
// 使用示例     ipm_store(g_param.ipm_h);
//-------------------------------------------------------------------------------------------------------------------
void ipm_store(float h[9]);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把图像坐标映射到俯视平面
// 参数说明     col/row          图像列/行
// 参数说明     x/y              输出，俯视平面坐标，y 向远端为负
// 返回参数     uint8            1=映射有效 0=落在消隐线以外，结果不可用
// 使用示例     if (ipm_to_bev(col, row, &x, &y)) { ... }
//-------------------------------------------------------------------------------------------------------------------
uint8 ipm_to_bev(float col, float row, float *x, float *y);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     把俯视平面坐标映射回图像
// 参数说明     x/y              俯视平面坐标
// 参数说明     col/row          输出，图像列/行
// 返回参数     uint8            1=映射有效
// 使用示例     if (ipm_to_img(x, y, &col, &row)) { ... }
//-------------------------------------------------------------------------------------------------------------------
uint8 ipm_to_img(float x, float y, float *col, float *row);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     用一帧直道图像现场标定逆透视矩阵
// 参数说明     l_near/r_near/row_near  近端角点的左右列与行号，来自边线直线拟合
// 参数说明     l_far/r_far/row_far     远端角点的左右列与行号，来自边线直线拟合
// 参数说明     len_ratio        两个采样行之间的地面距离 / 赛道宽度，见 IPM_LEN_RATIO
// 返回参数     uint8            1=标定成功，矩阵已生效
// 使用示例     ipm_calibrate(pts[0], pts[1], rn, pts[2], pts[3], rf, IPM_LEN_RATIO);
//-------------------------------------------------------------------------------------------------------------------
uint8 ipm_calibrate(float l_near, float r_near, float row_near,
                    float l_far,  float r_far,  float row_far, float len_ratio);

#endif // PERSPECTIVE_H
