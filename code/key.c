#include "key.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化按键扫描
// 参数说明     void
// 返回参数     void
// 使用示例     key_io_init();
//-------------------------------------------------------------------------------------------------------------------
void key_io_init(void)
{
    key_init(10);                                           // 按键扫描周期
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取并清除一次短按状态
// 参数说明     k               按键编号, KEY_1~KEY_4
// 返回参数     uint8           1=短按触发, 0=未触发
// 使用示例     uint8 pressed = key_short_pressed(KEY_1);
//-------------------------------------------------------------------------------------------------------------------
uint8 key_short_pressed(key_index_enum k)
{
    if (key_get_state(k) == KEY_SHORT_PRESS) {
        key_clear_state(k);
        return 1;
    }
    return 0;
}
